def text(a,x,y,s,cls=''): a.append(f'<text x="{x}" y="{y}" class="{cls}">{escape(s)}</text>')
def rect(a,x,y,w,h,fill='#e5ecf0'): a.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill}" stroke="#394854"/>')
def wire(a,points,color='#34495e',arrow=False): a.append(f'<polyline points="{points}" fill="none" stroke="{color}" stroke-width="2"'+(' marker-end="url(#arrow)"' if arrow else '')+'/>')
def dot(a,x,y):a.append(f'<circle cx="{x}" cy="{y}" r="4" fill="#34495e"/>')
def save(a,name): (HERE/name).write_text('\n'.join(a)+ '\n</svg>\n')

